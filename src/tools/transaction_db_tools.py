# transaction_db_tools.py
from typing import Dict
from sqlalchemy import create_engine
from db_model.transaction_model import TransLog
from config import settings
from utils import get_session
import pandas as pd
import logging

logger = logging.getLogger(__name__)

engine = create_engine(
    f"sqlite:///{settings.TRANSACTION_DIR / settings.TRANSACTION_DB}",
    echo=False,                                # Keep False for clean logs in production
    connect_args={"check_same_thread": False}  # Prevents thread errors in LangGraph workers
)

#----------------------------------------------------------------------------------------
def log_transaction(
    transaction: Dict[str, float|int],
    actual_class: int,
    pred_class: int,
    source_id: str
) -> tuple[int, str]:
    """
    Logs raw transaction features, class, and predicted class into SQLite database.
    Args:
        - transaction: feature-name and value in dict format [V1 to V28, Amount, HourT=Hour/2]
        - actual_class: actual class
        - pred_class: predicted class
        - source_id: source id currently real or gen (but can be consider as customer-id in future)
    Returns:
        The auto-incremented index of the inserted row, and string version of timestamp up to sec
    Raises:
        Exception: Re-raises any exception caught during processing after logging.
    """
    try:
        with get_session(engine) as session:
            new_entry = TransLog(
                V1=transaction.get("V1", 0.0),
                V2=transaction.get("V2", 0.0),
                V3=transaction.get("V3", 0.0),
                V4=transaction.get("V4", 0.0),
                V5=transaction.get("V5", 0.0),
                V6=transaction.get("V6", 0.0),
                V7=transaction.get("V7", 0.0),
                V8=transaction.get("V8", 0.0),
                V9=transaction.get("V9", 0.0),
                V10=transaction.get("V10", 0.0),
                V11=transaction.get("V11", 0.0),
                V12=transaction.get("V12", 0.0),
                V13=transaction.get("V13", 0.0),
                V14=transaction.get("V14", 0.0),
                V15=transaction.get("V15", 0.0),
                V16=transaction.get("V16", 0.0),
                V17=transaction.get("V17", 0.0),
                V18=transaction.get("V18", 0.0),
                V19=transaction.get("V19", 0.0),
                V20=transaction.get("V20", 0.0),
                V21=transaction.get("V21", 0.0),
                V22=transaction.get("V22", 0.0),
                V23=transaction.get("V23", 0.0),
                V24=transaction.get("V24", 0.0),
                V25=transaction.get("V25", 0.0),
                V26=transaction.get("V26", 0.0),
                V27=transaction.get("V27", 0.0),
                V28=transaction.get("V28", 0.0),
                Amount=transaction.get("Amount", 0.0),
                HourT=transaction.get("Hour/2", 0), # In real-scenario, this field can be extracted from timestamp (but here is generated by other rule)
                actual_class = actual_class,
                pred_class = pred_class,
                source_id =source_id
            )
            session.add(new_entry)
            session.flush()  # Populates new_entry.index prior to commit
            timestamp_str = new_entry.timestamp.strftime("%Y-%m-%d %H:%M:%S")
            return new_entry.index, timestamp_str
    except Exception as e:
        logger.error(f"Error in log_transaction: {e}")
        raise

#----------------------------------------------------------------------------------------
def get_transaction_df()->pd.DataFrame:
    """
    get transaction data in data-frame format
    Args:
        - None
    Returns:
        pandas dataframe contains transaction log
    Raises:
        Exception: Re-raises any exception caught during processing after logging.
    """
    try:
        table_name = TransLog.__tablename__ #Direct Attribute Access
        #[NOTE] we can also use metadata: table_name = TransLog.__table__.name
        df = pd.read_sql_table(table_name, engine)
        return df
    except Exception as e:
        logger.error(f"Error in get_transaction_df: {e}")
        raise
